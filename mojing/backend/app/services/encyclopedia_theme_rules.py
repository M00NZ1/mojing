"""
百科「题材锁」：按百科库名称/描述匹配**单一主题材**，约束 LLM 批量生成用语，
避免官场出现修仙阶位、西幻出现金丹、都市出现宗门等跨库串味。

规则按「先匹配更具体的题材」顺序只命中一条主锁，再追加通用尾注。
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from ..models import WorldEncyclopediaModel

# 各题材：本库允许的力量/等级轴 + 明确禁止的其它题材用语（摘要版，写入 prompt）
_TAIL = (
    "【通用尾注】\n"
    "· 本条仅服务于当前百科库，不要为其它世界观埋伏笔、借用其它世界的专有等级或组织形态。\n"
    "· 若本库已有「境界/职级/体系」条目，新条目必须与之相容，不得另起一套冲突主轴。\n"
)


def theme_addon_for_encyclopedia(enc: "WorldEncyclopediaModel") -> str:
    """返回附加到批量生成 prompt 的硬性约束（可能多段：主锁 + 通用尾注）。"""
    name = (enc.name or "").strip()
    tags = (getattr(enc, "genre_tags", None) or "").strip()
    desc = (getattr(enc, "description", None) or "").strip()
    wp = (getattr(enc, "world_prompt", None) or "").strip()
    blob = f"{name}\n{tags}\n{desc}\n{wp}"

    primary = _primary_theme_block(name, blob)
    if not primary:
        primary = _fallback_block(name, blob)
    return f"{primary}\n{_TAIL}".strip()


def _primary_theme_block(name: str, blob: str) -> str:
    n, b = name, blob
    # —— 顺序：先长后短、先特异后泛化，保证只命中一条 ——

    if "洪荒" in n or "神话洪荒" in b:
        return (
            "【题材锁 — 洪荒神话】\n"
            "· 力量与位阶用语：道行、劫数、气运、功德、洞天、灵根、灵宝、族群、量劫等，须与本库已有设定一致。\n"
            "· 禁止主导叙事：现代公务员职级体系、公司法务流程、互联网产品迭代、赛博黑客等作为「升级主轴」。\n"
            "· 禁止把其它题材的等级轴写进本条目（如 DND 法术环、战锤阿斯塔特连队编制、都市 KPI 等），除非本条明确写跨界事件。\n"
        )

    if "玄幻" in n or "万族" in n or "苍穹" in n:
        return (
            "【题材锁 — 玄幻万族】\n"
            "· 等级/力量：灵海、法相、天门、圣境、帝境、血脉、神通等，须与本库境界体系一致；禁止偷换成科举功名或现代职级当修炼阶。\n"
            "· 禁止主导：官场公文流、校园考试分、克苏鲁疯狂检定、战锤连队表等作为本条核心升级语言。\n"
            "· 禁止混入东方古典修仙专有套话与本库已弃用的冲突设定（若与「古典修仙库」重复专名，请改写为原创变体）。\n"
        )

    if any(k in n for k in ("古典修仙", "修仙世界", "修真界", "九天十地")) or (
        "修仙" in n and "江湖" not in n
    ):
        return (
            "【题材锁 — 古典修仙 / 修真】\n"
            "· 等级轴：炼气、筑基、金丹、元婴等须与本库一致；资源用灵石、丹药、法宝、宗门、秘境、天劫等语境。\n"
            "· 禁止主导：现代公司职级、公务员处级科级、西幻 MP/法术环、战锤连队编制、都市合同条款作为修为隐喻主轴。\n"
            "· 禁止把玄幻万族专有阶名与本库修仙阶名混成一套（除非本条写明确双体系碰撞）。\n"
        )

    if "武侠" in n or "江湖" in n:
        return (
            "【题材锁 — 武侠江湖】\n"
            "· 等级/实力：内功深浅、招式造诣、门派辈分、江湖声望；可用本库「武学境界」条目中的阶名（初窥、登堂、炉火等）。\n"
            "· 禁止：炼气筑基金丹元婴化神、灵根丹田、天劫渡劫、法宝飞剑宗门秘境等**修仙**体系用语当成本世界等级。\n"
            "· 禁止把西幻魔法位阶、现代格斗赛事积分、官场职级写成人物「武学境界」的同义替换。\n"
        )

    if "古武" in n or "国术" in n or "武道巅峰" in n:
        return (
            "【题材锁 — 传统古武 / 国术】\n"
            "· 等级轴：整劲、明劲、暗劲、化劲等**肉身劲力**表述；可写擂台、师承、伤病、训练。\n"
            "· 禁止：修仙阶位、魔法位阶、灵能等级、阿斯塔特改造阶段、克苏鲁 SAN 值当国术段位。\n"
            "· 「抱丹」等词仅作武术隐喻，不得展开为修仙金丹体系。\n"
        )

    if "穿越古代" in n or "架空王朝" in n:
        return (
            "【题材锁 — 穿越古代】\n"
            "· 允许：科举功名、品秩官职、户籍路引、武术（非修仙）、农商手工业与时代限制。\n"
            "· 禁止：炼气筑基金丹元婴、宗门秘境天劫、魔法位阶、星际跃迁等作为本世界默认力量语言。\n"
            "· 若写官制，「等级」指官阶功名，不得写成修炼境界。\n"
        )

    if any(k in n for k in ("官场", "权谋", "制度权谋")) or ("官场" in b and "制度" in b):
        return (
            "【题材锁 — 官场 / 制度权谋】\n"
            "· 「等级」「阶位」「实力」仅指官职品秩、编制职级、权责范围、考核与任免结果。\n"
            "· 禁止：炼气筑基金丹元婴、灵根丹田、法宝飞剑、宗门秘境、天劫神通、玄幻血脉、魔法环位等。\n"
            "· 叙事资源：会议、批示、流程、预算、项目、审计、舆情、问责、材料、派系与政商关系。\n"
        )

    if "校园" in n or "青春" in n:
        return (
            "【题材锁 — 校园青春】\n"
            "· 成长与「等级」：学业、体能、社团职务、考试名次、声誉与压力；禁止写成修仙境界或职场 P8。\n"
            "· 禁止：筑基金丹、魔法学院年级、战锤连队、克苏鲁神话神祇真名体系主导校园日常。\n"
        )

    if any(k in n for k in ("都市", "异能纪元")):
        return (
            "【题材锁 — 都市 / 异能】\n"
            "· 冲突与能力：职业、资本、技术、舆情、法律、异能设定须符合现实或本库已声明的近未来规则。\n"
            "· 禁止：修仙阶位、魔法环位、道行劫数、阿斯塔特连队、旧日支配者神名仪式等作为默认解释。\n"
        )

    if any(k in n for k in ("西幻", "DND", "费伦", "艾瑟兰", "冒险大陆")):
        return (
            "【题材锁 — 传统西幻】\n"
            "· 力量：职业、魔法学派、祝福、诅咒、装备、地下城层级；用语与 DND/西幻常见概念相容但勿照抄版权专有名词。\n"
            "· 禁止：筑基金丹元婴灵根、道行劫数、处级科级、赛博义体等级等混用为魔法位阶。\n"
        )

    if "战锤" in n or "40K" in n or "帝国编年史" in n:
        return (
            "【题材锁 — 战锤 40K 风】\n"
            "· 组织与力量：帝国机构、阿斯塔特、星界军、亚空间与科技宗教等本库语境。\n"
            "· 禁止把修仙阶位、DND 环位、现代公务员职级、校园考试分写成本世界力量主轴。\n"
        )

    if "克苏鲁" in n or "旧日" in n:
        return (
            "【题材锁 — 克苏鲁神话风】\n"
            "· 恐怖与未知：调查、疯狂、异教、遗迹、不可名状之影响；勿写可量化修仙等级或游戏化战力值主导。\n"
            "· 禁止：金丹元婴、法术环、星际跃迁、战锤连队表作为本条核心。\n"
        )

    if "星战" in n or ("银河" in n and "帝国" in n and "传奇" in n):
        return (
            "【题材锁 — 星球大战风】\n"
            "· 科幻设定：舰队、原力、政权、种族与太空航行逻辑；勿引入修仙宗门或 DND 神系。\n"
        )

    if any(k in n for k in ("科幻", "星际联邦", "星际")) or "星际联邦" in b:
        return (
            "【题材锁 — 科幻 / 星际】\n"
            "· 科技、工程、政治与资源约束；禁止用修仙境界、魔法环位、古代科举品秩解释星际文明能力。\n"
        )

    if "无限流" in n or "主神" in n or "诸天流" in n or "万界" in n:
        return (
            "【题材锁 — 无限 / 诸天】\n"
            "· 若本条描写**某一任务世界**，该世界内等级/组织须与该世界类型自洽，不得把官场职级写进修仙副本、也不得把金丹写进纯科幻任务。\n"
            "· 主神空间 / 轮回者侧可用任务评价、兑换与权限，但不得用单一外题材等级轴概括所有世界。\n"
        )

    return ""


def _fallback_block(name: str, blob: str) -> str:
    """未命中上述题材时：仍禁止明显串味。"""
    if not name and not blob:
        return _TAIL.strip()
    return (
        "【题材锁 — 未分类百科】\n"
        f"· 根据百科库名称与描述推断主题材，所有专有等级、组织、资源须与该主题材一致。\n"
        f"· 禁止把明显属于其它题材主轴的用语（修仙金丹、魔法环位、处级职级、阿斯塔特连队等）当作本世界默认体系。\n"
    )
