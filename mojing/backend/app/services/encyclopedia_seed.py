def seed_preset_encyclopedias():
    """首次启动时导入预设百科库和条目。"""
    with SessionLocal() as db:
        _seed_universal_template(db)
        seed_curated_source_encyclopedias(db)
        for enc_data in PRESET_ENCYCLOPEDIAS:
            if enc_data["name"] in DEPRECATED_SEED_ENCYCLOPEDIA_NAMES:
                continue
            existing = db.scalar(select(WorldEncyclopediaModel).where(WorldEncyclopediaModel.name == enc_data["name"]))
            if existing:
                continue
            enc = WorldEncyclopediaModel(
                name=enc_data["name"],
                description=enc_data["description"],
                is_official=enc_data.get("is_official", 0),
            )
            db.add(enc)
            db.flush()
            for entry_data in enc_data.get("entries", []):
                entry = EncyclopediaEntryModel(
                    encyclopedia_id=enc.id,
                    title=entry_data["title"],
                    entry_type=entry_data["entry_type"],
                    summary=entry_data.get("summary", ""),
                    content=entry_data.get("content", ""),
                    tags=entry_data.get("tags", ""),
                    is_featured=entry_data.get("is_featured", 0),
                    sort_order=entry_data.get("sort_order", 0),
                    meta_json=entry_data.get("meta_json", {}),
                )
                db.add(entry)
        db.commit()

        # 第二遍：批量生成扩展数据（为已有百科库补充大量条目；须在同一 Session 内）
        _generate_batch_entries(db)


def _generate_batch_entries(db: Session) -> None:
    """对每个有生成器的百科库依次补充条目；每库一批写入后单独 commit，再处理下一库。"""
    from .encyclopedia_generator import DESTINATIONS

    for enc_name in DESTINATIONS:
        enc = db.scalar(select(WorldEncyclopediaModel).where(WorldEncyclopediaModel.name == enc_name))
        if not enc:
            continue
        existing_titles = set(
            row for row in db.scalars(
                select(EncyclopediaEntryModel.title).where(EncyclopediaEntryModel.encyclopedia_id == enc.id)
            ).all() if row
        )
        new_entries = append_generated_entries(enc_name, existing_titles)
        if not new_entries:
            continue
        for entry_data in new_entries:
            db.add(EncyclopediaEntryModel(
                encyclopedia_id=enc.id,
                title=entry_data["title"],
                entry_type=entry_data["entry_type"],
                summary=entry_data.get("summary", ""),
                content=entry_data.get("content", ""),
                tags=entry_data.get("tags", ""),
                is_featured=entry_data.get("is_featured", 0),
                sort_order=entry_data.get("sort_order", 0),
                meta_json=entry_data.get("meta_json", {}),
            ))
        db.commit()


def _seed_universal_template(db):
    existing = db.scalar(
        select(WorldEncyclopediaModel).where(WorldEncyclopediaModel.name == UNIVERSAL_TEMPLATE_ENCYCLOPEDIA["name"])
    )
    if existing is None:
        existing = WorldEncyclopediaModel(
            name=UNIVERSAL_TEMPLATE_ENCYCLOPEDIA["name"],
            description=UNIVERSAL_TEMPLATE_ENCYCLOPEDIA["description"],
            is_official=UNIVERSAL_TEMPLATE_ENCYCLOPEDIA.get("is_official", 1),
        )
        db.add(existing)
        db.flush()
    else:
        existing.description = UNIVERSAL_TEMPLATE_ENCYCLOPEDIA["description"]
        existing.is_official = UNIVERSAL_TEMPLATE_ENCYCLOPEDIA.get("is_official", existing.is_official)

    existing_entries = {
        item.title: item
        for item in db.scalars(
            select(EncyclopediaEntryModel).where(EncyclopediaEntryModel.encyclopedia_id == existing.id)
        )
    }
    template_titles = {entry_data["title"] for entry_data in UNIVERSAL_TEMPLATE_ENTRIES}
    for title, row in list(existing_entries.items()):
        if title not in template_titles and (row.meta_json or {}).get("verification_status") == "template":
            db.delete(row)
            existing_entries.pop(title, None)

    for entry_data in UNIVERSAL_TEMPLATE_ENTRIES:
        row = existing_entries.get(entry_data["title"])
        if row is None:
            db.add(
                EncyclopediaEntryModel(
                    encyclopedia_id=existing.id,
                    title=entry_data["title"],
                    entry_type=entry_data["entry_type"],
                    summary=entry_data.get("summary", ""),
                    content=entry_data.get("content", ""),
                    tags=entry_data.get("tags", ""),
                    is_featured=entry_data.get("is_featured", 0),
                    sort_order=entry_data.get("sort_order", 0),
                    meta_json=entry_data.get("meta_json", {}),
                )
            )
            continue
        if (row.meta_json or {}).get("verification_status") == "template":
            row.entry_type = entry_data["entry_type"]
            row.summary = entry_data.get("summary", row.summary)
            row.content = entry_data.get("content", row.content)
            row.tags = entry_data.get("tags", row.tags)
            row.is_featured = entry_data.get("is_featured", row.is_featured)
            row.sort_order = entry_data.get("sort_order", row.sort_order)
            row.meta_json = entry_data.get("meta_json", row.meta_json)
    db.commit()
