def append_generated_entries(encyclopedia_name: str, existing_titles: set[str]) -> list[dict]:
    """为指定百科库生成新条目，跳过已存在的标题。"""
    gen = GENERATORS.get(encyclopedia_name)
    if not gen:
        return []
    all_entries = gen()
    new_entries = [e for e in all_entries if e["title"] not in existing_titles]
    return new_entries
