def seed_curated_source_encyclopedias(db: Session) -> None:
    _delete_deprecated_seed_encyclopedias(db)
    for enc_data in CURATED_SOURCE_ENCYCLOPEDIAS:
        enc = db.scalar(select(WorldEncyclopediaModel).where(WorldEncyclopediaModel.name == enc_data["name"]))
        if enc is None:
            enc = WorldEncyclopediaModel(
                name=enc_data["name"],
                description=enc_data["description"],
                is_official=enc_data.get("is_official", 0),
            )
            db.add(enc)
            db.flush()
        else:
            enc.description = enc_data["description"]
            enc.is_official = enc_data.get("is_official", enc.is_official)

        _delete_template_entries_from_playable_pack(db, enc.id)
        existing_by_title = {
            row.title: row
            for row in db.scalars(
                select(EncyclopediaEntryModel).where(EncyclopediaEntryModel.encyclopedia_id == enc.id)
            )
        }
        starter_entries = [_with_seed_pack(entry, enc_data["name"]) for entry in enc_data.get("entries", [])]
        extra_entries = [_with_seed_pack(entry, enc_data["name"]) for entry in EXTRA_ORIGINAL_ENTRIES.get(enc_data["name"], [])]
        for sort_order, entry_data in enumerate([*starter_entries, *extra_entries]):
            row = existing_by_title.get(entry_data["title"])
            if row is not None and (row.meta_json or {}).get("original_seed"):
                row.entry_type = entry_data["entry_type"]
                row.summary = entry_data.get("summary", row.summary)
                row.content = entry_data.get("content", row.content)
                row.tags = entry_data.get("tags", row.tags)
                row.is_featured = entry_data.get("is_featured", row.is_featured)
                row.sort_order = sort_order
                row.meta_json = entry_data.get("meta_json", row.meta_json)
                continue
            if row is None:
                db.add(
                    EncyclopediaEntryModel(
                        encyclopedia_id=enc.id,
                        title=entry_data["title"],
                        entry_type=entry_data["entry_type"],
                        summary=entry_data.get("summary", ""),
                        content=entry_data.get("content", ""),
                        tags=entry_data.get("tags", ""),
                        is_featured=entry_data.get("is_featured", 0),
                        sort_order=sort_order,
                        meta_json=entry_data.get("meta_json", {}),
                    )
                )


def _delete_deprecated_seed_encyclopedias(db: Session) -> None:
    rows = list(
        db.scalars(
            select(WorldEncyclopediaModel).where(WorldEncyclopediaModel.name.in_(DEPRECATED_SEED_ENCYCLOPEDIA_NAMES))
        )
    )
    for row in rows:
        db.delete(row)
    if rows:
        db.flush()


def _delete_template_entries_from_playable_pack(db: Session, encyclopedia_id: int) -> None:
    template_titles = {entry["title"] for entry in UNIVERSAL_TEMPLATE_ENTRIES}
    rows = list(
        db.scalars(
            select(EncyclopediaEntryModel).where(
                EncyclopediaEntryModel.encyclopedia_id == encyclopedia_id,
                EncyclopediaEntryModel.title.in_(template_titles),
            )
        )
    )
    for row in rows:
        meta = row.meta_json or {}
        if meta.get("verification_status") == "template" or meta.get("source_trust_level") == "template":
            db.delete(row)
    if rows:
        db.flush()


def _with_seed_pack(entry_data: dict, pack_name: str) -> dict:
    item = deepcopy(entry_data)
    meta = deepcopy(item.get("meta_json") or {})
    meta["seed_pack"] = pack_name
    meta["seed_version"] = SEED_VERSION
    meta.setdefault("original_seed", True)
    meta.setdefault("preserve_user_input", True)
    item["meta_json"] = meta
    return item
